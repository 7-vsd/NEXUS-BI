def _table(df: pd.DataFrame, status_col: str | None = None, max_rows: int = 500) -> str:
    df = df.head(max_rows)
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in df.columns)
    rows = []
    for _, r in df.iterrows():
        cells = []
        for c in df.columns:
            v = r[c]
            if isinstance(v, float):
                v = f"{v:,.4f}".rstrip("0").rstrip(".") if pd.notna(v) else ""
            elif v is None or (not isinstance(v, str) and pd.isna(v)):
                v = ""
            cls = f' class="{v}"' if status_col and c == status_col else ""
            cells.append(f"<td{cls}>{html.escape(str(v))}</td>")
        rows.append("<tr>" + "".join(cells) + "</tr>")
    return f"<table><thead><tr>{head}</tr></thead><tbody>{''.join(rows)}</tbody></table>"


def write_quality_report(path: Path, inventory: pd.DataFrame, checks: pd.DataFrame,
                         profile: pd.DataFrame, cleaning_log: pd.DataFrame | None = None) -> Path:
    total = len(checks)
    passed = int((checks.status == "PASS").sum())
    warns = int((checks.status == "WARN").sum())
    notes = int((checks.status == "NOTE").sum())
    fails = int((checks.status == "FAIL").sum())
    issues = checks[checks.status != "PASS"].sort_values(["status", "failed_rows"], ascending=[True, False])
    cards = "".join(
        f'<div class="card"><div class="v">{v}</div><div class="l">{l}</div></div>'
        for v, l in [(f"{inventory.rows.sum():,}", "Source rows"), (len(inventory), "Source files"),
                     (total, "Checks run"), (passed, "Passed"), (warns, "Warnings"), (notes, "Notes"), (fails, "Errors")]
    )
    sections = [
        f"<h2>Executive summary</h2><div class='cards'>{cards}</div>",
        "<div class='note'>Findings below are computed directly from the supplied Olist CSV files. "
        "Raw files are never modified; corrections are applied in the staging/processed layers and are listed in the cleaning log.</div>",
        "<h2>Source inventory</h2>" + _table(inventory),
        "<h2>Issues requiring attention</h2>" + (_table(issues, "status") if len(issues) else "<p>No issues.</p>"),
    ]
    if cleaning_log is not None and len(cleaning_log):
        sections.append("<h2>Cleaning &amp; transformation log</h2>" + _table(cleaning_log))
    sections += [
        "<h2>All data-quality checks</h2>" + _table(checks, "status"),
        "<h2>Column profile</h2>" + _table(profile, max_rows=1000),
    ]
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    doc = f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<title>NEXUS BI – Data Quality Report</title><style>{_CSS}</style></head><body>
<header><h1>NEXUS BI · Data Quality &amp; Profiling Report</h1>
<p>Olist Brazilian E-Commerce dataset · generated {ts}</p></header>
<main>{''.join(sections)}</main>
<footer>Generated by src/validation/report.py · NEXUS BI</footer></body></html>"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(doc, encoding="utf-8")
    return path
