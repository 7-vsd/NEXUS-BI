"""Data Quality – profiling, DQ checks, cleaning log, reconciliation."""
from __future__ import annotations

import plotly.express as px
import streamlit as st
import streamlit.components.v1 as components

from app.components.data import DataMissing, ROOT, load_csv
from app.components.theme import PALETTE
from app.components.ui import chart, kpi_row, note, page_header, section

page_header("Data Quality", "Source inventory, automated checks, cleaning actions and SQL ↔ Python reconciliation.")
try:
    inv = load_csv("reports/data_quality/source_inventory.csv")
    chk = load_csv("reports/data_quality/dq_checks.csv")
    clog = load_csv("reports/data_quality/cleaning_log.csv")
except DataMissing as exc:
    st.error(str(exc)); st.stop()

kpi_row([dict(label="Source rows", value=f"{inv.rows.sum():,}", accent=True),
         dict(label="Checks", value=str(len(chk))),
         dict(label="Passed", value=str(int((chk.status == 'PASS').sum()))),
         dict(label="Warnings", value=str(int((chk.status == 'WARN').sum()))),
         dict(label="Errors", value=str(int((chk.status == 'FAIL').sum())))])

c1, c2 = st.columns([1, 1.3])
with c1:
    section("Source inventory")
    st.dataframe(inv[["dataset", "file", "rows", "columns", "size_mb"]], hide_index=True, width="stretch")
with c2:
    section("Checks by status")
    s = chk.groupby(["dataset", "status"]).size().reset_index(name="checks")
    fig = px.bar(s, x="dataset", y="checks", color="status",
                 color_discrete_map={"PASS": PALETTE["green"], "WARN": PALETTE["amber"], "NOTE": PALETTE["blue"],
                                     "FAIL": PALETTE["red"]})
    chart(fig, 300)

section("Issues found (non-passing checks)")
status = st.multiselect("Status", ["WARN", "NOTE", "FAIL"], default=["WARN", "FAIL", "NOTE"])
st.dataframe(chk[chk.status.isin(status)][["dataset", "check", "column", "failed_rows", "failed_pct", "status", "detail"]]
             .sort_values("failed_rows", ascending=False), hide_index=True, width="stretch")

section("Cleaning & transformation log")
st.dataframe(clog, hide_index=True, width="stretch")

section("SQL warehouse ↔ Python reconciliation")
try:
    rec = load_csv("reports/sql_results/_reconciliation.csv")
    st.dataframe(rec, hide_index=True, width="stretch")
    if (rec.status == "PASS").all():
        st.success(f"All {len(rec)} reconciliation checks pass.")
    else:
        st.error(f"{int((rec.status != 'PASS').sum())} reconciliation checks fail.")
except DataMissing:
    note("Reconciliation not run yet (requires PostgreSQL): `python -m src.pipeline --stage analytics`.")

html_path = ROOT / "reports" / "data_quality" / "data_quality_report.html"
if html_path.exists():
    with st.expander("Full HTML data-quality report"):
        # Report is generated by this project (trusted content)
        if hasattr(st, "iframe"):
            st.iframe(html_path, height=700)
        else:  # Streamlit < 1.50
            components.html(html_path.read_text(encoding="utf-8"), height=700, scrolling=True)
        st.download_button("Download HTML report", html_path.read_bytes(), "data_quality_report.html", "text/html")
